// Helper to normalize Persian text for flexible matching
export function normalizePersianText(input: string): string {
  if (!input) return '';
  return input
    .trim()
    .replace(/[\u200c\u200b\uFEFF]/g, '') // remove zero-width non-joiners for uniform match
    .replace(/[ي]/g, 'ی')
    .replace(/[ك]/g, 'ک')
    .replace(/[ة]/g, 'ه')
    .replace(/[آ]/g, 'ا')
    .replace(/[\s\u00A0]+/g, '') // remove spaces for comparison
    .toLowerCase();
}

export function checkAnswerMatch(userInput: string, level: ProverbLevel): boolean {
  const normUser = normalizePersianText(userInput);
  if (!normUser) return false;

  const candidates = [
    level.proverb,
    level.targetAnswer,
    ...(level.alternativeAnswers || [])
  ];

  for (const cand of candidates) {
    const normCand = normalizePersianText(cand);
    if (normUser === normCand) return true;
    // Check if user entered the key proverb keywords
    if (normUser.length >= 4 && normCand.includes(normUser)) return true;
    if (normCand.length >= 4 && normUser.includes(normCand)) return true;
  }

  return false;
}
